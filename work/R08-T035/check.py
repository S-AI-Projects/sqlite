#!/usr/bin/env python3
"""Automated checker for the ISBN‑Verifier reference implementation.

It validates that the maintained reference solution (the example SQL) produces
passing results for all enabled tests defined in ``isbn-verifier_test.sql``.
The script:

1. Reads ``.meta/config.json`` to discover the solution, test and example
   files.
2. Copies the entire ``exercises/practice/isbn-verifier`` directory (including
   hidden files) into a temporary workspace.
3. Executes the SQLite test suite with ``sqlite3 -bail``.
4. Parses the generated ``output.json`` and asserts that every test entry has
   ``status == "pass"`` and that at least one test was run.
5. Stores the ``output.json`` and a small ``versions.txt`` file in
   ``work/R08-T035`` for reproducibility.

The runner does **not** modify the repository working tree; all operations are
performed in the temporary copy.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

def main() -> None:
    repo_root = Path(__file__).resolve().parents[2]
    exercise_dir = repo_root / "exercises" / "practice" / "isbn-verifier"
    config_path = exercise_dir / ".meta" / "config.json"
    if not config_path.is_file():
        sys.exit("config.json not found")
    config = json.loads(config_path.read_text())
    # Resolve relative paths from the exercise directory
    solution_rel = config["files"]["solution"][0]
    test_rel = config["files"]["test"][0]
    example_rel = config["files"]["example"][0]
    solution_path = exercise_dir / solution_rel
    test_path = exercise_dir / test_rel
    example_path = exercise_dir / example_rel
    # Create a temporary copy of the whole exercise (including hidden files)
    with tempfile.TemporaryDirectory() as tmp_dir:
        tmp_path = Path(tmp_dir)
        shutil.copytree(exercise_dir, tmp_path / "isbn-verifier", dirs_exist_ok=True)
        # Overwrite the learner stub with the maintained reference implementation
        shutil.copy2(example_path, tmp_path / "isbn-verifier" / "isbn-verifier.sql")
        # Run the test suite inside the temporary copy
        cwd = tmp_path / "isbn-verifier"
        # SQLite will read the test file which itself reads other files relative to cwd
        cmd = ["sqlite3", "-bail", test_path.name]
        result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
        if result.returncode != 0:
            sys.exit(f"sqlite3 failed: {result.stderr}")
        # Load output.json generated by the test suite
        output_file = cwd / "output.json"
        if not output_file.is_file():
            sys.exit("output.json not found after test run")
        try:
            output_data = json.loads(output_file.read_text())
        except Exception as e:
            sys.exit(f"Failed to parse output.json: {e}")
        if not isinstance(output_data, list) or len(output_data) == 0:
            sys.exit("No test entries found in output.json")
            # Derive expected test count from .meta/tests.toml
    tests_toml_path = exercise_dir / ".meta" / "tests.toml"
    try:
        toml_content = tests_toml_path.read_text()
    except Exception as e:
        sys.exit(f"Failed to read tests.toml: {e}")
    # Count number of section headers like [uuid]
    import re
    expected_count = len(re.findall(r"^\[.*\]$", toml_content, flags=re.MULTILINE))
    # Verify count matches output entries
    actual_count = len(output_data)
    print(f"Expected test count: {expected_count}, actual count: {actual_count}")
    if actual_count != expected_count:
        sys.exit(f"Test count mismatch: expected {expected_count}, got {actual_count}")

        failed = [t for t in output_data if t.get("status") != "pass"]
        if failed:
            sys.exit(f"Some tests failed: {failed}")
        # Save evidence files for the coursework PR
        evidence_dir = repo_root / "work" / "R08-T035"
        evidence_dir.mkdir(parents=True, exist_ok=True)
        shutil.copy2(output_file, evidence_dir / "output.json")
        # Store version information
        versions = []
        # SQLite version
        ver = subprocess.run(["sqlite3", "--version"], capture_output=True, text=True)
        versions.append(f"sqlite3 {ver.stdout.strip()}")
        # Python version
        versions.append(f"python {sys.version.split()[0]}")
        (evidence_dir / "versions.txt").write_text("\n".join(versions))
        # Also copy the refactored example for reference
        shutil.copy2(example_path, evidence_dir / "refactored_example.sql")
        # Copy the original baseline (should already exist from earlier steps)
        # Finally, print summary
        print(f"Executed {len(output_data)} tests – all passed.")

if __name__ == "__main__":
    main()
