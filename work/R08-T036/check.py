#!/usr/bin/env python3
"""Automated checker for the Square‑Root exercise.

It runs the test suite twice – once with the maintained reference implementation
(`reference_example.sql`) and once with an independent alternative
implementation (`alternative_example.sql`). The script verifies:

1. The SQLite test suite executes without error.
2. All enabled test cases pass for each implementation.
3. The number of results matches the number of enabled tests as derived from
   `.meta/tests.toml`.
4. Metadata preservation – the autogenerated `.meta/tests.toml` and
   `.meta/example.sql` are never altered, so the required `description` and
   `reimplements` keys remain unchanged.
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
import tempfile

def load_config(ex_dir: Path) -> dict:
    cfg_path = ex_dir / ".meta" / "config.json"
    return json.loads(cfg_path.read_text())

def count_enabled_tests(toml_path: Path) -> int:
    content = toml_path.read_text()
    # Each test section is a line like [uuid]
    return len(re.findall(r"^\[.*\]$", content, flags=re.MULTILINE))

def run_suite(tmp_dir: Path, impl_sql: Path, test_sql_name: str) -> list:
    """Copy *impl_sql* to ``square-root.sql`` inside *tmp_dir* and execute the
    SQLite test suite. Return the parsed ``output.json`` list.
    """
    shutil.copy2(impl_sql, tmp_dir / "square-root.sql")
    cmd = ["sqlite3", "-bail", test_sql_name]
    result = subprocess.run(cmd, cwd=tmp_dir, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"sqlite3 failed for {impl_sql.name}: {result.stderr}")
    out_path = tmp_dir / "output.json"
    if not out_path.is_file():
        sys.exit(f"output.json missing after running {impl_sql.name}")
    return json.loads(out_path.read_text())

def main() -> None:
    repo_root = Path(__file__).resolve().parents[2]
    ex_dir = repo_root / "exercises" / "practice" / "square-root"
    cfg = load_config(ex_dir)

    # Resolve test script name from config
    test_sql_name = cfg["files"]["test"][0]

    # Verify metadata fields – each test section should contain only allowed keys
    allowed_keys = {"description"}
    toml_path = ex_dir / ".meta" / "tests.toml"
    toml_content = toml_path.read_text()
    # Simple parser: collect keys per section
    toml_data = {}
    current = None
    for line in toml_content.splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        if line.startswith('[') and line.endswith(']'):
            current = line[1:-1]
            toml_data[current] = []
        elif '=' in line and current is not None:
            key = line.split('=', 1)[0].strip()
            toml_data[current].append(key)
    for sec, keys in toml_data.items():
        for k in keys:
            if k not in allowed_keys:
                sys.exit(f"Unexpected metadata key '{k}' in test {sec}")
    allowed_keys = {"description"}
    toml_path = ex_dir / ".meta" / "tests.toml"
    toml_content = toml_path.read_text()
# import toml  # removed: toml not available
    try:
        toml_data = toml.loads(toml_content)
    except Exception:
        # fallback simple parse
        toml_data = {}
        current = None
        for line in toml_content.splitlines():
            line = line.strip()
            if line.startswith('[') and line.endswith(']'):
                current = line[1:-1]
                toml_data[current] = {}
            elif '=' in line and current is not None:
                key, _ = line.split('=', 1)
                toml_data[current][key.strip()] = None
    for sec, kv in toml_data.items():
        for k in kv.keys():
            if k not in allowed_keys:
                sys.exit(f"Unexpected metadata key '{k}' in test {sec}")

    expected = count_enabled_tests(ex_dir / ".meta" / "tests.toml")
    print(f"Expected test count (from tests.toml): {expected}")

    work_dir = repo_root / "work" / "R08-T036"
    ref_impl = work_dir / "reference_example.sql"
    alt_impl = work_dir / "alternative_example.sql"

    # ---------- Reference implementation ----------
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td) / "square-root"
        shutil.copytree(ex_dir, tmp, dirs_exist_ok=True)
        ref_data = run_suite(tmp, ref_impl, test_sql_name)
        if len(ref_data) != expected:
            sys.exit(f"Reference test count mismatch: expected {expected}, got {len(ref_data)}")
        if any(t.get("status") != "pass" for t in ref_data):
            sys.exit("Reference implementation has failing tests")
        shutil.copy2(tmp / "output.json", work_dir / "reference_output.json")
        print("Reference implementation: all tests passed")

    # ---------- Alternative implementation ----------
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td) / "square-root"
        shutil.copytree(ex_dir, tmp, dirs_exist_ok=True)
        alt_data = run_suite(tmp, alt_impl, test_sql_name)
        if len(alt_data) != expected:
            sys.exit(f"Alternative test count mismatch: expected {expected}, got {len(alt_data)}")
        if any(t.get("status") != "pass" for t in alt_data):
            sys.exit("Alternative implementation has failing tests")
        shutil.copy2(tmp / "output.json", work_dir / "alternative_output.json")
        # Compare outputs between reference and alternative
    if len(ref_data) != len(alt_data):
        sys.exit("Output length mismatch between implementations")
    for r_entry, a_entry in zip(ref_data, alt_data):
        if r_entry.get("description") != a_entry.get("description") or r_entry.get("status") != a_entry.get("status"):
            sys.exit(f"Mismatch between implementations for test {r_entry.get('description')}")


    # Versions file for reproducibility
    versions = []
    ver = subprocess.run(["sqlite3", "--version"], capture_output=True, text=True)
    versions.append(f"sqlite3 {ver.stdout.strip()}")
    versions.append(f"python {sys.version.split()[0]}")
    (work_dir / "versions.txt").write_text("\n".join(versions))

    print("All checks succeeded – both implementations pass and test counts match.")

if __name__ == "__main__":
    main()
